"""The UI's fonts: Inter Tight (assets/fonts/InterTight[wght].ttf, SIL OFL 1.1, the font Felucca uses) rasterised
into 4-bit anti-aliased glyphs, in the format gfx.c draws (felucca_font_t: proportional, 2 px a byte, each glyph
the font's full height, its bitmap starting `pad` px left of the pen).

  tools/gen_font.py            -> firmware/gen/felucca_font.h   (needs Pillow)

Faces: FONT_S labels and values (13 px, weight 500), FONT_M headers (15 px, 600), FONT_L big text (26 px, 600),
each ASCII 32..126."""
import math
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TTF = ROOT / "assets" / "fonts" / "InterTight[wght].ttf"
OUT = ROOT / "firmware" / "gen" / "felucca_font.h"
#        name  px  weight height baseline tracking(px)
FACES = [("S", 13, 500, 16, 12, 0.2), ("M", 15, 600, 18, 14, 0.2), ("L", 26, 600, 32, 26, 0.0)]
PAD = 2


def face(name, px, weight, h, base, track):
    f = ImageFont.truetype(str(TTF), px)
    f.set_variation_by_axes([weight])
    adv, bw, off, data = [], [], [], bytearray()
    for code in range(32, 127):
        ch = chr(code)
        a = f.getlength(ch) + track
        l, _, r, _ = f.getbbox(ch, anchor="ls")
        w = max(1, int(math.ceil(max(r, a))) + PAD + 1)
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((PAD, base), ch, font=f, fill=255, anchor="ls")
        px_ = img.load()
        while w > 1 and all(px_[w - 1, y] == 0 for y in range(h)):   # trim empty columns on the right
            w -= 1
        adv.append(max(1, int(round(a))))
        bw.append(w)
        off.append(len(data))
        for y in range(h):
            row = [min(15, (px_[x, y] + 8) // 17) for x in range(w)]
            if w % 2:
                row.append(0)
            for x in range(0, len(row), 2):
                data.append(row[x] << 4 | row[x + 1])
    def arr(t, n, v):
        lines = [", ".join(str(x) for x in v[i:i + 24]) for i in range(0, len(v), 24)]
        return f"static const {t} FONT_{name}_{n}[{len(v)}] = {{\n    " + ",\n    ".join(lines) + "};\n"
    return (arr("uint8_t", "DATA", list(data)) + arr("uint16_t", "OFF", off) + arr("uint8_t", "ADV", adv)
            + arr("uint8_t", "BW", bw)
            + f"static const felucca_font_t FONT_{name} = {{ {h}, {PAD}, 32, 126, FONT_{name}_ADV, FONT_{name}_BW, "
              f"FONT_{name}_OFF, FONT_{name}_DATA }};\n\n"), len(data)


def main():
    parts, sizes = [], []
    for fc in FACES:
        s, n = face(*fc)
        parts.append(s)
        sizes.append(f"{fc[0]} {n} B")
    OUT.write_text("/* generated by tools/gen_font.py from Inter Tight (assets/fonts, SIL OFL 1.1): "
                   "FONT_S 13 px, FONT_M 15 px, FONT_L 26 px, ASCII 32..126 */\n#pragma once\n#include <stdint.h>\n"
                   f"#define FONT_PAD {PAD}\n\n" + "".join(parts))
    print("fonts:", ", ".join(sizes), "->", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
