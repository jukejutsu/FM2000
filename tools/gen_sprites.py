"""The UI's sprites, drawn here once: the knob (a metal knob seen from above, after the FM-1's own: a dark rim, a
domed cap lit from the top left, a shine, a pointer at one o'clock and a soft shadow down and right), in two
sizes. Each sprite is RGB565 and an alpha in sixteenths, blended onto whatever is under it (fm2k.c, sprite()).

  tools/gen_sprites.py         -> firmware/gen/fm2k_sprites.h"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware" / "gen" / "fm2k_sprites.h"

# the design system's metal (fm2k.c's C_METAL_*)
M0, M4 = (230, 234, 242), (92, 98, 118)
RIM, INK = (43, 47, 64), (14, 18, 38)


def mix(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


def knob(R):
    n = int(math.ceil(R)) * 2 + 4                   # room for the shadow
    c = n // 2 - 1
    rgb = [[(0, 0, 0)] * n for _ in range(n)]
    a = [[0.0] * n for _ in range(n)]
    def put(x, y, col, al):                         # over what is there (in the sprite)
        if not (0 <= x < n and 0 <= y < n) or al <= 0: return
        a0 = a[y][x]
        na = al + a0 * (1 - al)
        rgb[y][x] = mix(rgb[y][x], col, al / na if na else 0)
        a[y][x] = na
    for y in range(n):                              # the shadow first, under it all
        for x in range(n):
            d = math.hypot(x - c - 1.2, y - c - 1.6)
            put(x, y, (0, 0, 0), max(0.0, min(1.0, R + .6 - d)) * .35)
    for y in range(n):
        for x in range(n):
            i, j = x - c, y - c
            d = math.hypot(i, j)
            al = max(0.0, min(1.0, R + .5 - d))
            if al <= 0: continue
            if d > R - 1.2:
                col = RIM
            else:
                l = max(0.0, min(1.0, .62 - .5 * (i / R * .7 + j / R * .7)))
                col = mix(M4, M0, l)
                if math.hypot(i + 2, j + 2.2) < 1.6: col = mix(col, (255, 255, 255), .7)
            put(x, y, col, al)
    for k in range(1, int(R) - 1):                  # the pointer
        put(c + round(k * .5), c - k, INK, 1.0)
    return n, rgb, a


def c565(col):
    r, g, b = (int(round(v)) for v in col)
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


def emit(name, R):
    n, rgb, a = knob(R)
    px = [c565(rgb[y][x]) for y in range(n) for x in range(n)]
    al = [int(round(a[y][x] * 16)) for y in range(n) for x in range(n)]
    rows = lambda v, f: ",\n    ".join(", ".join(f(x) for x in v[i:i + n]) for i in range(0, len(v), n))
    return (f"static const uint16_t {name}_PX[{n * n}] = {{\n    {rows(px, lambda x: f'0x{x:04X}')}}};\n"
            f"static const uint8_t {name}_A[{n * n}] = {{\n    {rows(al, str)}}};\n"
            f"static const sprite_t {name} = {{{n}, {n}, {name}_PX, {name}_A}};\n\n")


def main():
    OUT.write_text("/* generated by tools/gen_sprites.py: the knob, small (the footer) and large (EDT) */\n#pragma once\n"
                   "#include <stdint.h>\ntypedef struct { uint8_t w, h; const uint16_t *px; const uint8_t *a; } sprite_t;\n\n"
                   + emit("SPR_KNOB", 6.5) + emit("SPR_KNOB_L", 7.5))
    print("sprites ->", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
